#!/usr/bin/env node
// Scans every source file for FontAwesome usages and emits a static data
// module that the Dev Tools "Icon Audit" page renders. Covers:
//   1. <FontAwesome name="..." /> literal attributes
//   2. <FontAwesome name={expr} /> where expr is a string literal
//   3. icon: '...' object literals that feed dynamic name={s.icon} renderers
//      (config maps, metadata tables, etc.)
//   4. Dynamic name={expr} usages we cannot statically resolve — recorded with
//      a null icon so reviewers can spot icons that only exist via runtime data.
//
// Usage:  node scripts/generate-icon-audit.mjs   (writes lib/devtools/icon-audit-data.ts)
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const ROOT = resolve(process.cwd());
const SRC_DIRS = ['app', 'components', 'lib', 'contexts', 'hooks', 'types', 'utils'];
const IGNORE_DIRS = new Set(['node_modules', '.git', '.expo', 'dist', 'website', '.claude']);
const IGNORE_FILES = new Set(['lib/devtools/icon-audit-data.ts', 'lib/devtools/icon-audit-data.json']);
const OUT_FILE = join(ROOT, 'lib', 'devtools', 'icon-audit-data.ts');
const OUT_JSON = join(ROOT, 'lib', 'devtools', 'icon-audit-data.json');

const ICON_TAG_RE = /<FontAwesome\b[\s\S]*?>/g;
const NAME_ATTR_RE = /name\s*=\s*("([^"]*)"|'([^']*)'|\{([\s\S]*?)\})/g;
const ICON_PROP_RE = /\bicon\s*:\s*("([^"]*)"|'([^']*)'|\{([\s\S]*?)\})/g;
const STRING_LITERAL_RE = /^['"]([^'"]*)['"]$/;

function lineOf(text, index) {
  return text.slice(0, index).split('\n').length;
}

function normalizeRel(p) {
  return relative(ROOT, p).replace(/\\/g, '/');
}

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (IGNORE_DIRS.has(entry.name)) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.(tsx|ts)$/.test(entry.name)) out.push(full);
  }
  return out;
}

const files = SRC_DIRS.flatMap((d) => {
  const full = join(ROOT, d);
  try {
    return statSync(full).isDirectory() ? walk(full) : [];
  } catch {
    return [];
  }
});

const byIcon = new Map(); // icon -> { file, line, kind, snippet }[]
const dynamicUsages = [];

function record(icon, file, line, kind, snippet) {
  if (icon === null || icon === undefined) {
    dynamicUsages.push({ file, line, kind, snippet });
    return;
  }
  if (!byIcon.has(icon)) byIcon.set(icon, []);
  byIcon.get(icon).push({ file, line, kind, snippet });
}

for (const file of files) {
  if (IGNORE_FILES.has(normalizeRel(file))) continue;
  const text = readFileSync(file, 'utf8');
  const rel = normalizeRel(file);

  // 1 & 2 & 4: <FontAwesome ... /> tags
  let m;
  while ((m = ICON_TAG_RE.exec(text)) !== null) {
    const tag = m[0];
    const tagStart = m.index;
    let nm;
    while ((nm = NAME_ATTR_RE.exec(tag)) !== null) {
      // [full, whole, dqInner, sqInner, braceInner]
      const [, , dqInner, sqInner, braceInner] = nm;
      const line = lineOf(text, tagStart + nm.index);
      if (dqInner !== undefined) {
        record(dqInner.trim(), rel, line, 'attribute', tag.replace(/\s+/g, ' ').slice(0, 120));
      } else if (sqInner !== undefined) {
        record(sqInner.trim(), rel, line, 'attribute', tag.replace(/\s+/g, ' ').slice(0, 120));
      } else {
        const inner = (braceInner || '').trim();
        const lit = inner.match(STRING_LITERAL_RE);
        if (lit) {
          record(lit[1], rel, line, 'attribute', tag.replace(/\s+/g, ' ').slice(0, 120));
        } else {
          record(null, rel, line, 'dynamic', tag.replace(/\s+/g, ' ').slice(0, 120));
        }
      }
    }
    NAME_ATTR_RE.lastIndex = 0;
  }

  // 3: icon: '...' object literals (metadata maps feeding dynamic renders)
  let p;
  while ((p = ICON_PROP_RE.exec(text)) !== null) {
    const [, , dqInner, sqInner, braceInner] = p;
    const line = lineOf(text, p.index);
    const snippet = text.slice(Math.max(0, p.index - 30), p.index + 40).replace(/\s+/g, ' ');
    if (dqInner !== undefined) {
      record(dqInner.trim(), rel, line, 'metadata', snippet);
    } else if (sqInner !== undefined) {
      record(sqInner.trim(), rel, line, 'metadata', snippet);
    } else {
      const inner = (braceInner || '').trim();
      const lit = inner.match(STRING_LITERAL_RE);
      if (lit) record(lit[1], rel, line, 'metadata', snippet);
    }
  }
}

const entries = [...byIcon.entries()]
  .filter(([icon]) => icon && icon.trim().length > 0)
  .map(([icon, usages]) => ({ icon, usages }))
  .sort((a, b) => a.icon.localeCompare(b.icon));

const totalUsages = entries.reduce((n, e) => n + e.usages.length, 0) + dynamicUsages.length;

const out = `// GENERATED by scripts/generate-icon-audit.mjs — DO NOT EDIT BY HAND.
// Re-run:  node scripts/generate-icon-audit.mjs
// Every FontAwesome usage found across the app, grouped by icon name.

export type IconAuditKind = 'attribute' | 'metadata' | 'dynamic';

export interface IconAuditUsage {
  file: string;
  line: number;
  kind: IconAuditKind;
  snippet: string;
}

export interface IconAuditEntry {
  icon: string;
  usages: IconAuditUsage[];
}

export interface IconAuditMeta {
  generatedAt: string;
  totalIcons: number;
  totalUsages: number;
  dynamicUsages: number;
  filesScanned: number;
}

export const ICON_AUDIT_META: IconAuditMeta = {
  generatedAt: '${new Date().toISOString()}',
  totalIcons: ${entries.length},
  totalUsages: ${totalUsages},
  dynamicUsages: ${dynamicUsages.length},
  filesScanned: ${files.length},
};

export const ICON_AUDIT: IconAuditEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(OUT_FILE, out, 'utf8');
console.log(`Wrote ${OUT_FILE}`);

const jsonOut = {
  generatedAt: new Date().toISOString(),
  meta: {
    totalIcons: entries.length,
    totalUsages,
    dynamicUsages: dynamicUsages.length,
    filesScanned: files.length,
  },
  dynamic: dynamicUsages,
  icons: entries,
};
writeFileSync(OUT_JSON, JSON.stringify(jsonOut, null, 2) + '\n', 'utf8');
console.log(`Wrote ${OUT_JSON}`);
console.log(`  files scanned : ${files.length}`);
console.log(`  icons found   : ${entries.length}`);
console.log(`  total usages  : ${totalUsages} (${dynamicUsages.length} dynamic/unresolved)`);
